def compact_ledger(data,reg):
    """Share repeated source/test/default evidence; preserve exact frozen facts."""
    data['registry'] = reg
    sites, index = [], {}
    test_ids = {t['path']:'T'+str(i+1).zfill(4) for i,t in enumerate(data['existing_tests'])}
    for test in data['existing_tests']:
        test['id']=test_ids[test['path']]
        test['test_sites']=[[t['name'],t['line'],t.get('ignored_after_test_attribute',False)] for t in test.pop('tests')]
    contract_keys=['consumer_obligation','test_link_strength','unresolved_domains','migration_state']
    data['family_row_defaults'] = {k:data['families'][0][k] for k in contract_keys}
    data['family_row_defaults']['supported_domain_contract'] = data['families'][0]['supported_overload_evidence']['exact_domain_definition']
    data['family_row_defaults']['arity_contract'] = data['families'][0]['supported_overload_evidence']['sql_ast_arity_and_guard_definition']
    for row in data['families']:
        for key in contract_keys: row.pop(key)
        row['registry_names'] = list(row.pop('registry_arities'))
        row['dispatch_site_ids']=[]
        for site in row.pop('dispatch_evidence'):
            key=json.dumps(site,sort_keys=True)
            if key not in index:
                index[key]='S'+str(len(sites)+1).zfill(4)
                sites.append({'id':index[key],**site,'source_line':source(site['path']).splitlines()[site['line']-1].strip()})
            row['dispatch_site_ids'].append(index[key])
        row['test_module_ids']=[test_ids[p] for p in row.pop('existing_test_source_links')]
        row.pop('native_source_paths') # union of dispatch site paths and domain_profile.sources
        row['native_source_rule']='Union of dispatch site paths and shared domain_profile.sources; fixed SHA input hashes retained.'
        row['supported_overload_evidence'].pop('exact_domain_definition')
        row['supported_overload_evidence'].pop('sql_ast_arity_and_guard_definition')
        if row['exclusion_reason'] is None: row.pop('exclusion_reason')
        if row['domain_notes'] is None: row.pop('domain_notes')
    data['dispatch_sites']=sites
    return data

def serialize(data):
    # Tables get one complete JSON row per line; profiles/definitions remain
    # conventionally indented. This is ordinary parseable JSON, not JSONL.
    tables={'families','dispatch_sites','existing_tests','native_source_inventory','dispatch_function_extents','suggested_test_commands'}
    parts=[]
    for key,value in data.items():
        if key in tables:
            encoded='[\n'+',\n'.join('    '+json.dumps(v,ensure_ascii=False,separators=(',', ':')) for v in value)+'\n  ]'
        else:
            encoded=json.dumps(value,indent=2,ensure_ascii=False).replace('\n','\n  ')
        parts.append('  '+json.dumps(key)+': '+encoded)
    return '{\n'+',\n'.join(parts)+'\n}\n'


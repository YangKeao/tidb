def lex_mask(text, hide_strings):
    # Rust comments (including nested block comments), raw/byte/ordinary
    # strings, chars versus lifetimes. Offsets and line numbers are retained.
    chars=list(text)
    n=len(text)
    i=0
    def blank(a,b):
        for j in range(a,b):
            if chars[j]!='\n': chars[j]=' '
    while i<n:
        start=i
        if text.startswith('//',i):
            end=text.find('\n',i)
            i=n if end<0 else end
            blank(start,i)
        elif text.startswith('/*',i):
            depth=1; i+=2
            while i<n and depth:
                if text.startswith('/*',i): depth+=1; i+=2
                elif text.startswith('*/',i): depth-=1; i+=2
                else: i+=1
            blank(start,i)
        else:
            raw=re.match(r'(?:br|r)(#*)"',text[i:]) if text[i] in 'br' and (i==0 or not (text[i-1].isalnum() or text[i-1]=='_')) else None
            if raw:
                closing='"'+raw[1]
                end=text.find(closing,i+len(raw[0]))
                i=n if end<0 else end+len(closing)
                if hide_strings: blank(start,i)
            elif text[i]=='"':
                i+=1
                while i<n:
                    if text[i]=='\\': i+=2
                    elif text[i]=='"': i+=1; break
                    else: i+=1
                if hide_strings: blank(start,min(i,n))
            elif text[i]=="'":
                char=re.match(r"'(?:\\(?:u\{[0-9a-fA-F_]+\}|x[0-9a-fA-F]{2}|.)|[^'\\\n])'",text[i:])
                if char:
                    i+=len(char[0])
                    if hide_strings: blank(start,i)
                else: i+=1
            else: i+=1
    return ''.join(chars)

def clean_comments(text):
    return lex_mask(text,False)

def masked(text):
    return lex_mask(text,True)

def body(path, name, repo='tidb'):
    text = source(path, repo)
    mask = masked(text)
    start = re.search(r'\bfn\s+' + re.escape(name) + r'\s*(?:<[^\n]*>)?\s*\(', mask)
    if not start:
        raise ValueError((path, name))
    begin = mask.index('{', start.end())
    depth = 1
    end = begin + 1
    while depth:
        if mask[end] == '{': depth += 1
        elif mask[end] == '}': depth -= 1
        end += 1
    return text[begin:end], text[:begin].count('\n') + 1


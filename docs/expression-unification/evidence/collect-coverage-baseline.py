def registry():
    text = source(EXPR + 'builtin_registry.rs')
    return {m[1]: {'min': int(m[2]), 'max': None if m[3] == 'None' else int(m[4]),
                    'line': text[:m.start(1)].count('\n') + 1}
            for m in re.finditer(r'^\s*\("([^"\n]+)",\s*(\d+),\s*(None|Some\((\d+)\))\),', text, re.M)}

def candidates():
    reg = registry()
    allowed = set(reg) | EXTRA_NAMES
    found = collections.defaultdict(list)
    for short, functions in DISPATCH.items():
        path = EXPR + short
        for fn in functions:
            block, first = body(path, fn)
            clean = clean_comments(block)
            for m in re.finditer(r'"([A-Za-z_][A-Za-z_0-9]*)"', clean):
                name = m[1].lower()
                if name not in allowed and not name.startswith('cast_'): continue
                line = first + clean[:m.start()].count('\n')
                item = {'name': name, 'path': path, 'symbol': fn, 'line': line}
                if item not in found[canonical(name)]: found[canonical(name)].append(item)
    return reg, found


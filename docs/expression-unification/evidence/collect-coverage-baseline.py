def production_text(text):
    # Inline cfg(test) modules may occur in the middle of a production file.
    # Blank only those balanced modules, not everything after the first test.
    mask = masked(text)
    spans = []
    for m in re.finditer(r'#\[cfg\(test\)\]\s*(?:pub\s+)?mod\s+\w+\s*\{', mask):
        depth, end = 1, m.end()
        while depth:
            if mask[end]=='{': depth += 1
            elif mask[end]=='}': depth -= 1
            end += 1
        spans.append((m.start(),end))
    for start,end in reversed(spans):
        text = text[:start]+re.sub(r'[^\n]',' ',text[start:end])+text[end:]
    return text

